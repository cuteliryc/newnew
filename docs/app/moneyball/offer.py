def check(offer, competitor_analysis=None):
    """offer: {"text": "...", "checks": {ключ: true/false}}"""
    marks = offer.get("checks", {})
    passed = [(k, q) for k, q, _ in CHECKS if marks.get(k)]
    failed = [(k, q, fix) for k, q, fix in CHECKS if not marks.get(k)]
    crowded, gaps = [], []
    if competitor_analysis and competitor_analysis.get("status") == "ok":
        for angle, m in competitor_analysis["angle_matrix"].items():
            if m["status"].startswith("паритет"):
                crowded.append(angle)
            elif m["status"].startswith("разрыв"):
                gaps.append(angle)
    return {
        "passed": len(passed), "total": len(CHECKS),
        "fix_first": [{"check": q, "how": fix} for _, q, fix in failed[:4]],
        "all_missing": [q for _, q, _ in failed],
        "crowded_angles": crowded, "gap_angles": gaps,
        "tests": [f"Оффер A (текущий) vs B ({fix.lower()})" for _, _, fix in failed[:2]],
        "note": "Чек-лист — практика, не закон. Решение о лучшем оффере — тестом (layer=offer).",
    }
